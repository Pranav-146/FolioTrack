-- FolioTrack initial schema.
-- Money uses NUMERIC (exact decimal), never floating point.

CREATE TABLE users (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name         VARCHAR(100)   NOT NULL,
    email        VARCHAR(255)   NOT NULL UNIQUE,
    cash_balance NUMERIC(15, 2) NOT NULL CHECK (cash_balance >= 0),
    created_at   TIMESTAMPTZ    NOT NULL DEFAULT now()
);

CREATE TABLE instruments (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    symbol        VARCHAR(10)    NOT NULL UNIQUE,
    name          VARCHAR(100)   NOT NULL,
    current_price NUMERIC(12, 2) NOT NULL CHECK (current_price > 0),
    updated_at    TIMESTAMPTZ    NOT NULL DEFAULT now()
);

CREATE TABLE holdings (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id       BIGINT         NOT NULL REFERENCES users (id),
    instrument_id BIGINT         NOT NULL REFERENCES instruments (id),
    -- A holding that drops to 0 shares is deleted, so stored quantity is always positive
    quantity      INTEGER        NOT NULL CHECK (quantity > 0),
    avg_cost      NUMERIC(12, 2) NOT NULL CHECK (avg_cost > 0),
    UNIQUE (user_id, instrument_id)
);

CREATE TABLE orders (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id            BIGINT         NOT NULL REFERENCES users (id),
    instrument_id      BIGINT         NOT NULL REFERENCES instruments (id),
    side               VARCHAR(4)     NOT NULL CHECK (side IN ('BUY', 'SELL')),
    quantity           INTEGER        NOT NULL CHECK (quantity > 0),
    price_at_execution NUMERIC(12, 2) NOT NULL,
    status             VARCHAR(10)    NOT NULL CHECK (status IN ('FILLED', 'REJECTED')),
    rejection_reason   VARCHAR(255),
    created_at         TIMESTAMPTZ    NOT NULL DEFAULT now()
);

CREATE TABLE transactions (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT         NOT NULL REFERENCES users (id),
    order_id   BIGINT         NOT NULL REFERENCES orders (id),
    type       VARCHAR(4)     NOT NULL CHECK (type IN ('BUY', 'SELL')),
    -- Always positive; type says whether cash went out (BUY) or came in (SELL)
    amount     NUMERIC(15, 2) NOT NULL CHECK (amount > 0),
    created_at TIMESTAMPTZ    NOT NULL DEFAULT now()
);

-- History endpoints query "this user's rows, newest first", so index exactly that.
CREATE INDEX idx_orders_user_created ON orders (user_id, created_at DESC);
CREATE INDEX idx_transactions_user_created ON transactions (user_id, created_at DESC);
